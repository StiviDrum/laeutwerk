const LANGUAGES: Record<string, Strings> = { en, de };

export interface Localizer {
  lang: string;
  t(key: StringKey, vars?: Record<string, string | number>): string;
  weekdayShort(index: number): string;
  monthShort(index: number): string;
}

const localizers = new Map<string, Localizer>();

/** Localizer for a HA language (cached: one stable object per language). */
export function localizer(language: string | undefined): Localizer {
  const key = language ?? "en";
  let l = localizers.get(key);
  if (!l) {
    const strings = LANGUAGES[key.split("-")[0].toLowerCase()] ?? en;
    l = {
      lang: key,
      t(k, vars) {
        let text: string = strings[k] ?? en[k];
        for (const [name, value] of Object.entries(vars ?? {})) {
          text = text.replace(`{${name}}`, String(value));
        }
        return text;
      },
      weekdayShort: (i) => strings.weekdays_short[i],
      monthShort: (i) => strings.months[i],
    };
    localizers.set(key, l);
  }
  return l;
}
